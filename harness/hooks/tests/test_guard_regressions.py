def run_group(group, name, payload):
    if group == "guard":
        return dangerous_ops_guard.decide(payload)
    if group == "openpyxl":
        return openpyxl_guard.decide(payload)
    if group == "frontmatter":
        return frontmatter_guard.decide(payload)
    if group == "read-deny":
        environ = {} if name.endswith("-flag-off") else {"HARNESS_READ_DENY": "1"}
        return read_deny.decide(payload, environ)
    if group == "write-deny":
        # shipped off: the group replays against its own structure file, not the pinned default
        structure = json.loads((FIXTURES / "write-deny-structure.json").read_text(encoding="utf-8"))
        return write_deny.decide(payload, TESTS.parents[2], structure)
    raise AssertionError("unknown fixture group " + group)


def expected_verdict(name):
    prefix = name.split("-", 1)[0]
    return {"bypass": "deny", "deny": "deny", "advise": "advisory", "allow": "silence"}[prefix]


def fixtures():
    for path in sorted(FIXTURES.glob("*/*.json")):
        yield path.parent.name, path.stem, path


class FixtureRegressions(unittest.TestCase):
    def test_at_least_the_required_number_of_guard_fixtures(self):
        names = {path.stem for path in (FIXTURES / "guard").glob("*.json")}
        assert len(names) >= MIN_GUARD_FIXTURES, len(names)
        missing = [name for name in REQUIRED_GUARD_CLASSES if name not in names]
        assert not missing, missing

    def test_every_fixture_has_an_expected_file_and_vice_versa(self):
        fixture_keys = {(group, name) for group, name, _ in fixtures()}
        expected_keys = {(path.parent.name, path.stem) for path in EXPECTED.glob("*/*.expected")}
        assert fixture_keys == expected_keys, fixture_keys ^ expected_keys

    def test_every_fixture_matches_its_expected_bytes(self):
        for group, name, path in fixtures():
            with self.subTest(group=group, name=name):
                payload = json.loads(path.read_text(encoding="utf-8"))
                out = run_group(group, name, payload)
                actual = ((out + "\n") if out else "").encode("utf-8")
                expected = (EXPECTED / group / (name + ".expected")).read_bytes()
                assert actual == expected

    def test_every_fixture_produces_the_verdict_its_name_states(self):
        for group, name, path in fixtures():
            with self.subTest(group=group, name=name):
                payload = json.loads(path.read_text(encoding="utf-8"))
                out = run_group(group, name, payload)
                verdict = expected_verdict(name)
                if verdict == "silence":
                    assert out is None
                    continue
                assert out is not None
                value = json.loads(out)
                if verdict == "deny":
                    assert set(value) == {"hookSpecificOutput"}
                    specific = value["hookSpecificOutput"]
                    assert set(specific) == DENY_KEYS
                    assert specific["hookEventName"] == "PreToolUse"
                    assert specific["permissionDecision"] == "deny"
                    reason = specific["permissionDecisionReason"]
                    assert REASON_SHAPE.match(reason), reason
                else:
                    assert "permissionDecision" not in json.dumps(value)
                    assert set(value) in ({"systemMessage"}, {"hookSpecificOutput"})

    def test_guard_fixtures_agree_with_the_dispatcher(self):
        for group, name, path in fixtures():
            if group not in ("guard", "openpyxl"):
                continue
            with self.subTest(name=name):
                result = dispatch.dispatch("PreToolUse", path.read_text(encoding="utf-8"), runtime="codex")
                denied = bool(result and result["hookSpecificOutput"].get("permissionDecision") == "deny")
                assert denied == (expected_verdict(name) == "deny")

    def test_fixture_payloads_carry_the_envelope_fields(self):
        for group, name, path in fixtures():
            with self.subTest(name=name):
                payload = json.loads(path.read_text(encoding="utf-8"))
                assert payload["hook_event_name"] in ("PreToolUse", "PostToolUse")
                assert isinstance(payload["tool_name"], str)
                assert isinstance(payload["tool_input"], dict)


class GuardBehaviorTests(unittest.TestCase):
    def denied(self, command):
        return dangerous_ops_guard.classify(dangerous_ops_guard.strip_safe_contexts(command))[0]

    def test_sql_prose_versus_execution_context(self):
        assert not self.denied('grep -rn "drop table" migrations/')
        assert not self.denied("echo drop table sessions")
        assert self.denied("echo 'drop table sessions;'")
        assert self.denied("sqlite3 app.db 'drop table sessions'")

    def test_credential_read_requires_reader_plus_path_argument(self):
        assert self.denied("cat " + ".env")
        assert self.denied("sudo cat " + ".env")
        assert self.denied("type " + ".env")
        assert not self.denied("cat " + ".env.template")
        assert not self.denied("ls -la " + ".env")
        assert not self.denied("echo $SECRET_TOKEN")

    def test_secret_path_set_includes_structure_outbound_globs(self):
        structure = {"outbound_globs": ["docs/private/**"]}
        assert dangerous_ops_guard.reads_secret("cat docs/private/notes.md", structure)
        assert not dangerous_ops_guard.reads_secret("cat docs/public/notes.md", structure)
        assert not dangerous_ops_guard.reads_secret("cat docs/private/notes.md", {"outbound_globs": []})

    def test_command_digest_is_over_the_raw_command(self):
        import hashlib
        command = "rm -rf /"
        out = dangerous_ops_guard.decide({"tool_name": "Bash", "tool_input": {"command": command}})
        digest = hashlib.sha256(command.encode("utf-8")).hexdigest()
        assert "[command-sha256:%s]" % digest in out

    def test_bare_force_push_is_protected_only_in_main_only_mode(self):
        # Fixture payloads cannot carry a custom structure.json, so the
        # branches-mode allow for a bare force push is covered here instead.
        main_only = {"git": {"mode": "main-only"}}
        branches = {"git": {"mode": "branches"}}
        assert dangerous_ops_guard.classify("git push -f", main_only)[0]
        assert dangerous_ops_guard.classify("git push -f origin", main_only)[0]
        assert not dangerous_ops_guard.classify("git push -f", branches)[0]
        assert not dangerous_ops_guard.classify("git push -f origin", branches)[0]
        # An explicit refspec is never "bare", regardless of mode.
        assert not dangerous_ops_guard.classify("git push -f origin feature", main_only)[0]

    def test_force_with_all_refs_is_protected_in_either_git_mode(self):
        branches = {"git": {"mode": "branches"}}
        assert dangerous_ops_guard.classify("git push --force --all origin", branches)[0]
        assert not dangerous_ops_guard.classify("git push --force origin feature", branches)[0]

    def test_a_refspec_is_classified_by_its_destination_side(self):
        assert not self.denied("git push --force origin main:feature")
        assert self.denied("git push --force origin feature:main")
        assert self.denied("git push --force origin HEAD~1:main")
        assert not self.denied("git push --force origin HEAD:feature")

    def test_a_lease_allows_a_push_but_never_a_protected_deletion(self):
        assert not self.denied("git push --force-with-lease origin main")
        assert self.denied("git push --force-with-lease origin :main")

    def test_an_unquoted_comment_is_not_an_argument(self):
        assert self.denied("git push --force origin main # --dry-run")
        assert not self.denied("git push --force origin main --dry-run # deploy")

    def test_single_quoted_text_is_inert_unless_a_shell_runs_the_string(self):
        assert not self.denied("echo 'git push --force origin main'")
        assert self.denied("bash -c 'git push --force origin main'")

    def test_delete_flags_and_operands_parse_in_any_order(self):
        assert self.denied("rm ../victim -rf")
        assert not self.denied("rm ../notes.txt -f")
        assert not self.denied("rm -rf ./build/../dist")

    def test_cancellation_is_symmetric_across_option_spellings(self):
        assert not self.denied("git push -f --no-force origin main")
        assert not self.denied("git push --force --no-force origin main")
        assert self.denied("git push -n --no-dry-run -f origin main")
        assert self.denied("git push --dry-run --no-dry-run -f origin main")

    def test_an_interpreter_call_is_a_read_but_prose_is_not(self):
        assert self.denied("""python -c "print(open('.env').read())" """)
        assert not self.denied("""python -c "open('.env', 'w').write('X=1')" """)
        assert not self.denied("""git commit -m "docs: open('.env') stays closed" """)

    def test_a_reserved_word_never_hides_the_command(self):
        assert self.denied("if true; then cat .env; fi")
        assert self.denied("while true; do cat .env; break; done")
        assert self.denied("builtin cat .env")

    def test_process_substitution_body_is_a_command(self):
        assert self.denied("cat <(cat .env)")
        assert self.denied("cat > >(cat .env)")
        assert not self.denied("cat <(cat README.md)")

    def test_a_comment_hides_nothing_after_the_line_break(self):
        assert self.denied("echo ok # explain" + chr(10) + "cat .env")
        assert not self.denied("echo ok # cat .env")


BS = chr(92)
BT = chr(96)


def _users_path(*names):
    """A drive-qualified Users path built from parts, so no literal drive-and-backslash shape appears in this file."""
    return "C" + ":" + BS + BS.join(("Users",) + names)


def _posix_home(*names):
    return "/" + "ho" + "me" + "".join("/" + n for n in names)


class PowerShellCoverageTests(unittest.TestCase):
    def ps(self, command):
        return dangerous_ops_guard.decide({"tool_name": "PowerShell", "tool_input": {"command": command}})

    def bash(self, command):
        return dangerous_ops_guard.decide({"tool_name": "Bash", "tool_input": {"command": command}})

    def test_powershell_force_push_main_denied(self):
        assert self.ps("git push --force origin main") is not None
        assert self.ps("git push -f origin main") is not None
        assert self.ps("git push --force-with-lease origin feature") is None

    def test_powershell_remove_item_drive_root_denied(self):
        assert self.ps("Remove-Item -Recurse -Force C:" + BS) is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path()) is not None

    def test_powershell_get_content_env_denied(self):
        assert self.ps("Get-Content .env") is not None
        assert self.ps("Get-Content README.md") is None

    def test_powershell_backtick_continuation_force_push_denied(self):
        assert self.ps("git push origin main " + BT + chr(10) + "  --force") is not None
        assert self.ps("git push origin main " + BT + chr(13) + chr(10) + "  --force") is not None
        assert self.ps("git push origin main " + BT + "  " + chr(10) + "  -f") is not None
        assert self.ps("git push origin feature " + BT + chr(10) + "  --force") is None
        # A backtick is a POSIX substitution in Bash: Bash handling is unchanged.
        assert self.bash("echo " + BT + "echo hi" + BT) is None

    def test_powershell_backtick_escape_is_dropped(self):
        assert self.ps("git push --for" + BT + "ce origin main") is not None
        # Single-quoted text stays inert.
        assert self.ps("Write-Output 'git push --force origin main " + BT + "'") is None

    def test_powershell_benign_set_allows(self):
        benign = [
            "git status",
            "git commit -m 'fix: tidy the parser'",
            "python harness/tools/lint.py --out build",
            "npm install",
            "npm run test",
            "Get-ChildItem -Recurse -Filter *.md",
            "Remove-Item -Recurse " + "." + BS + "build",
            "git commit -m @'" + chr(10) + "feat: add the thing" + chr(10) + chr(10) + "Body line." + chr(10) + "'@",
            'Write-Host "line one' + BT + 'nline two"',
        ]
        for command in benign:
            assert self.ps(command) is None, command

    def test_night_watch_ignores_powershell(self):
        # The guards other than the two opted in keep ignoring PowerShell: the dispatcher routes nothing for it.
        import dispatch
        assert dispatch.modules_for("PreToolUse", {"tool_name": "PowerShell"}) == []
        assert dispatch.modules_for("PostToolUse", {"tool_name": "PowerShell"}) == []

    def test_deep_descendant_of_a_home_directory_is_allowed(self):
        scratch = _users_path("alice", "AppData", "Local", "Temp", "run", "scratch", "tmp")
        assert self.ps('Remove-Item -Recurse -Force "' + scratch + '" -Confirm:$false') is None
        assert self.bash("rm -rf " + scratch.replace(BS, "/")) is None
        assert self.ps("Remove-Item -Recurse -Force " + scratch.replace(BS, "/")) is None
        assert self.bash("rm -rf " + _posix_home("alice", "work", "clone")) is None
        assert self.ps("Remove-Item -Recurse -Force " + _posix_home("alice", "work")) is None
        assert self.bash("rm -rf ~/work") is None

    def test_home_directory_itself_is_denied(self):
        for shell in (self.bash, self.ps):
            assert shell("rm -rf " + _posix_home("alice")) is not None
            assert shell("rm -rf " + _posix_home("alice") + "/") is not None
            assert shell("rm -rf '" + _posix_home("alice") + "'") is not None
            assert shell("rm -rf " + _users_path("alice").replace(BS, "/")) is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path("alice")) is not None
        assert self.ps('Remove-Item -Recurse -Force "' + _users_path("alice") + '"') is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path("ALICE").replace("Users", "USERS")) is not None

    def test_home_level_wildcards_are_denied(self):
        assert self.bash("rm -rf " + _posix_home("alice") + "/*") is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path("alice") + BS + "*") is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path("alice").replace(BS, "/") + "/*") is not None
        assert self.bash("rm -rf " + _posix_home() + "/*") is not None

    def test_users_root_is_denied(self):
        assert self.bash("rm -rf " + _posix_home()) is not None
        assert self.bash("rm -rf /Us" + "ers") is not None
        assert self.bash("rm -rf /Us" + "ers/") is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path()) is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path().replace(BS, "/")) is not None
        assert self.ps("Remove-Item -Recurse -Force " + _users_path() + BS + "*") is not None

    def test_home_tokens_are_still_denied(self):
        assert self.bash("rm -rf ~") is not None
        assert self.bash("rm -rf $HOME") is not None
        assert self.bash("rm -rf ${HOME}") is not None
        assert self.ps("Remove-Item -Recurse -Force $env:USERPROFILE") is not None
        assert self.ps("Remove-Item -Recurse -Force $env:HOMEPATH") is not None

    def test_other_roots_are_unchanged(self):
        assert self.bash("rm -rf /") is not None
        assert self.bash("rm -rf /usr/local/lib") is not None
        assert self.bash("rm -rf /etc") is not None
        assert self.ps("Remove-Item -Recurse -Force C:" + BS + "Windows" + BS + "Temp") is not None
        assert self.ps("Remove-Item -Recurse -Force $env:SystemRoot") is not None
        assert self.bash("rm -rf " + _posix_home("alice") + "/../..") is not None

    def test_recursive_chown_follows_the_same_root_rule(self):
        assert self.bash("chown -R alice " + _posix_home("alice")) is not None
        assert self.bash("chown -R alice " + _posix_home("alice", "project")) is None


    def test_globs_in_the_user_or_first_segment_are_denied(self):
        home = _posix_home("alice")
        for command in (
            "rm -rf " + home + "/**",
            "rm -rf " + home + "/?*",
            "rm -rf " + home + "/[a-z]*",
            "rm -rf " + home + "/{*,.*}",
            "rm -rf " + home + "/.*",
            "rm -rf " + _posix_home("*", ".config"),
            "rm -rf " + _users_path("*", "AppData").replace(BS, "/"),
            "chown -R me " + _posix_home("*", "x"),
        ):
            assert self.bash(command) is not None, command
        for command in (
            "Remove-Item -Recurse -Force " + _users_path("alice", "**"),
            "Remove-Item -Recurse -Force " + _users_path("alice", "?*"),
            "Remove-Item -Recurse -Force " + _users_path("alice", "[a-z]*"),
            "Remove-Item -Recurse -Force " + _users_path("alice", "{*,.*}"),
            "Remove-Item -Recurse -Force " + _users_path("alice", ".*"),
            "Remove-Item -Recurse -Force " + _users_path("*", "AppData"),
            "Remove-Item -Recurse -Force " + _posix_home("alice", "**"),
            "Remove-Item -Recurse -Force " + _posix_home("*", ".config"),
        ):
            assert self.ps(command) is not None, command
        # A glob deeper than the first segment below the home stays a descendant.
        assert self.bash("rm -rf " + home + "/project/build/*") is None

    def test_dot_segments_below_a_home_are_denied(self):
        home = _posix_home("alice")
        for command in ("rm -rf " + home + "/x/.", "rm -rf " + home + "/x/../y", "rm -rf " + home + "/./x",
                        "rm -rf " + home + "/../../etc", "chown -R me " + home + "/x/."):
            assert self.bash(command) is not None, command
        for command in ("Remove-Item -Recurse -Force " + _users_path("alice", "x") + BS + ".",
                        "Remove-Item -Recurse -Force " + _users_path("alice", "x", "..", "y"),
                        "Remove-Item -Recurse -Force " + _users_path("alice", "..", ".."),
                        "Remove-Item -Recurse -Force " + _users_path("alice", ".")):
            assert self.ps(command) is not None, command

    def test_doubled_backtick_does_not_hide_a_later_command(self):
        later = "git push --force origin main"
        assert self.ps('Write-Output "' + BT + BT + '"; ' + later) is not None
        assert self.ps("Write-Output " + BT + BT + "; " + later) is not None
        assert self.ps('Write-Output "' + BT + BT + '"; git status') is None

    def test_here_string_quotes_do_not_hide_a_later_command(self):
        later = "git push --force origin main"
        nl = chr(10)
        single = "git commit -m @'" + nl + "fix: don't break" + nl + "'@; " + later
        double = 'git commit -m @"' + nl + 'say "hi' + nl + '"@; ' + later
        assert self.ps(single) is not None
        assert self.ps(double) is not None
        assert self.ps(single.replace(nl, chr(13) + nl)) is not None
        # A benign message with apostrophes and quotes still passes.
        assert self.ps("git commit -m @'" + nl + "fix: don't break the parser's tests" + nl + "'@") is None
        assert self.ps('git commit -m @"' + nl + 'say "hi" and don' + chr(39) + 't' + nl + '"@') is None
        assert self.ps("git commit -m @'" + nl + "body" + nl + "'@; git status") is None
        # The text inside a here-string is data, not a command.
        assert self.ps("git commit -m @'" + nl + later + nl + "'@") is None

    def test_unterminated_here_string_does_not_crash(self):
        nl = chr(10)
        for text in ("git commit -m @'" + nl + "never closed", 'git commit -m @"' + nl + "open " + chr(34) + "quote",
                     "@'", "@'" + nl, "@" + chr(34)):
            assert self.ps(text) is None, text
        assert dangerous_ops_guard.powershell_normalize("x @'" + nl + "a'b") == "x '" + nl + "ab'"


