# Every fixture's expected verdict is written against the template's shipped
# structure (main-only git mode, default lanes). The libs under test default
# to load_structure(), which reads whatever structure.json the checkout the
# suite runs from actually ships; on an adopted host that can be "branches"
# mode or null lanes. HARNESS_STRUCTURE_FILE pins the loader to the fixed
# template default for the life of this module so fixture bytes stay
# deterministic on any host (test-only override, see hook_io's docstring).
_STRUCTURE_OVERRIDE = str((TESTS.parents[2] / "harness" / "tools" / "templates" / "structure.default.json").resolve())
_PRIOR_STRUCTURE_ENV = None


def setUpModule():
    global _PRIOR_STRUCTURE_ENV
    _PRIOR_STRUCTURE_ENV = os.environ.get("HARNESS_STRUCTURE_FILE")
    os.environ["HARNESS_STRUCTURE_FILE"] = _STRUCTURE_OVERRIDE


def tearDownModule():
    if _PRIOR_STRUCTURE_ENV is None:
        os.environ.pop("HARNESS_STRUCTURE_FILE", None)
    else:
        os.environ["HARNESS_STRUCTURE_FILE"] = _PRIOR_STRUCTURE_ENV

