#!/usr/bin/env python3
"""gen_manifest.py - generated views of the skill catalog and routing policy.

Scans every harness/skills/<name>/SKILL.md (and _vendor/<source>/<name>/SKILL.md),
reads the frontmatter, and writes:

    harness/skills/RESOLVER.md            one row per metadata.triggers phrase
    harness/registry/skill-index.json     machine-readable catalog (generated, untracked cache;
                                          --check tolerates its absence, never a stale copy)
    THIRD-PARTY.md                         one table row per harness/registry/sources.json entry

and refreshes the three generated routing views inside harness/rules/base-routing.md
(<!-- gen:routing-tasks -->, routing-profiles, routing-tools) when those markers exist.

Usage:
    python harness/tools/gen_manifest.py            # regenerate
    python harness/tools/gen_manifest.py --check    # exit 1 if anything would change
    python harness/tools/gen_manifest.py --licenses # print a tab-separated sources.json dump
                                                     # (for the scaffold's NOTICE; THIRD-PARTY.md
                                                     # itself is written by the default run above)

Marker syntax in docs:  <!-- gen:BLOCK-ID --> ... <!-- /gen:BLOCK-ID -->
Everything between the markers is machine-owned; do not hand-edit.

The skill count block in harness/CONTRACT.md is never written by this tool
(the contract is hand-authored); the lint compares the contract to
skill-index.json instead. Zero skills is a valid state: the resolver is then an
empty table with its header.
"""

