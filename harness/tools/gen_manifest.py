@dataclass
class Skill:
    name: str
    path: str
    status: str = ""
    description: str = ""
    packs: list[str] = field(default_factory=list)
    triggers: list[str] = field(default_factory=list)
    requires: list[str] = field(default_factory=list)
    distribution: str = ""
    license: str = ""
    notice: str | None = None
    neighbor: str = "none"
    neighbor_explicit: bool = False
    frontmatter: dict[str, Any] = field(default_factory=dict)
    problems: list[str] = field(default_factory=list)
    route_owner: str = ""


def skill_files(root: Path) -> list[Path]:
    base = Path(root) / SKILLS_DIR
    if not base.is_dir():
        return []
    files = sorted(path for path in base.glob("*/SKILL.md") if not path.parent.name.startswith("_"))
    files.extend(sorted(base.glob(f"{VENDOR_DIR}/*/*/SKILL.md")))
    return files


def _string_list(value: Any, label: str, problems: list[str]) -> list[str]:
    if value is None:
        return []
    if isinstance(value, str):
        value = [value]
    if not isinstance(value, list) or any(not isinstance(item, str) or not item.strip() for item in value):
        problems.append(f"{label} must be a list of non-empty strings")
        return []
    return [item.strip() for item in value]


def load_skill(root: Path, skill_md: Path) -> Skill:
    relative = skill_md.parent.relative_to(Path(root)).as_posix()
    skill = Skill(name=skill_md.parent.name, path=relative)
    try:
        text = skill_md.read_text(encoding="utf-8-sig")
    except OSError as exc:
        skill.problems.append(f"unreadable: {exc}")
        return skill
    frontmatter = parse_frontmatter(text)
    if frontmatter is None:
        skill.problems.append("missing frontmatter block")
        return skill
    skill.frontmatter = frontmatter
    name = frontmatter.get("name")
    if not isinstance(name, str) or not name.strip():
        skill.problems.append("name is required")
    elif name.strip() != skill_md.parent.name:
        skill.problems.append(f"name {name.strip()!r} does not match folder {skill_md.parent.name!r}")
    description = frontmatter.get("description")
    if not isinstance(description, str) or not description.strip():
        skill.problems.append("description is required")
    else:
        skill.description = description.strip()
        if "WHEN:" not in skill.description:
            skill.problems.append("description must contain 'WHEN:'")
    metadata = frontmatter.get("metadata")
    if not isinstance(metadata, dict):
        skill.problems.append("metadata block is required")
        metadata = {}
    skill.packs = _string_list(metadata.get("packs"), "metadata.packs", skill.problems)
    if "packs" not in metadata or not skill.packs:
        skill.problems.append("metadata.packs is required and must not be empty")
    for pack in skill.packs:
        if not KEBAB.match(pack):
            skill.problems.append(f"pack slug {pack!r} is not kebab-case")
    skill.triggers = _string_list(metadata.get("triggers"), "metadata.triggers", skill.problems)
    if "triggers" not in metadata or not skill.triggers:
        skill.problems.append("metadata.triggers is required and must not be empty")
    skill.requires = _string_list(metadata.get("requires"), "metadata.requires", skill.problems)
    status = metadata.get("status")
    if status not in VALID_STATUSES:
        skill.problems.append(f"metadata.status must be one of {', '.join(VALID_STATUSES)} (got {status!r})")
    else:
        skill.status = status
    distribution = metadata.get("distribution")
    if distribution not in VALID_DISTRIBUTIONS:
        skill.problems.append(
            f"metadata.distribution must be one of {', '.join(VALID_DISTRIBUTIONS)} (got {distribution!r})"
        )
    else:
        skill.distribution = distribution
    license_value = metadata.get("license")
    if license_value not in VALID_LICENSES:
        skill.problems.append(f"metadata.license must be one of {', '.join(VALID_LICENSES)} (got {license_value!r})")
    else:
        skill.license = license_value
    notice = metadata.get("notice")
    if notice is not None and not isinstance(notice, str):
        skill.problems.append("metadata.notice must be a string or null")
    else:
        skill.notice = notice
    neighbor = metadata.get("neighbor")
    if neighbor is not None:
        if not isinstance(neighbor, str) or not neighbor.strip():
            skill.problems.append("metadata.neighbor must be a skill name, none, or absent")
        else:
            skill.neighbor = neighbor.strip()
            skill.neighbor_explicit = True
    route_owner = metadata.get("route_owner")
    if isinstance(route_owner, str):
        skill.route_owner = route_owner.strip()
    return skill


def _neighbor_from_description(skill: Skill, names: set[str]) -> str:
    """The first existing skill named in the WHEN NOT clause, else none.

    This is the routing boundary the clause draws (where an adjacent intent
    goes), never a fallback for a deselected target or an absent capability.
    """
    match = re.search(r"WHEN NOT:(.*)", skill.description, re.DOTALL)
    if not match:
        return "none"
    for candidate in re.findall(r"(?:/|`)([a-z][a-z0-9-]*)`?", match.group(1)):
        if candidate in names and candidate != skill.name:
            return candidate
    return "none"


def scan_skills(root: Path = ROOT) -> list[Skill]:
    """Every skill in the catalog, sorted by name, with per-skill problems."""
    skills = [load_skill(root, path) for path in skill_files(root)]
    names = {skill.name for skill in skills}
    for skill in skills:
        if not skill.neighbor_explicit and skill.description:
            skill.neighbor = _neighbor_from_description(skill, names)
        if skill.neighbor != "none" and skill.neighbor not in names:
            skill.problems.append(f"metadata.neighbor {skill.neighbor!r} is not a skill")
        elif skill.neighbor == skill.name:
            skill.problems.append("metadata.neighbor names the skill itself")
    return sorted(skills, key=lambda item: item.name)


def status_tally(skills: list[Skill]) -> dict[str, int]:
    tally = {status: 0 for status in VALID_STATUSES}
    for skill in skills:
        if skill.status in tally:
            tally[skill.status] += 1
    return tally


# ---------------------------------------------------------------------------
# Generated outputs
# ---------------------------------------------------------------------------

def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def resolver_rows(skills: list[Skill]) -> list[tuple[str, str, str, str, str]]:
    rows = []
    for skill in sorted(skills, key=lambda item: (sorted(item.packs)[0] if item.packs else "~", item.name)):
        pack = ", ".join(sorted(skill.packs)) or "none"
        for trigger in skill.triggers:
            rows.append((trigger, skill.name, skill.neighbor, pack, skill.status or "unknown"))
    return rows


def render_resolver(skills: list[Skill]) -> str:
    lines = [RESOLVER_HEADER.rstrip("\n"), ""]
    lines.append("| " + " | ".join(RESOLVER_COLUMNS) + " |")
    lines.append("|" + "---|" * len(RESOLVER_COLUMNS))
    for trigger, target, neighbor, pack, status in resolver_rows(skills):
        neighbor_cell = "none" if neighbor == "none" else f"`{neighbor}`"
        lines.append(f"| \"{_cell(trigger)}\" | `{target}` | {neighbor_cell} | {_cell(pack)} | {status} |")
    return "\n".join(lines) + "\n"


def render_skill_index(skills: list[Skill]) -> str:
    index = {
        "schema_version": 1,
        "total": len(skills),
        "counts": status_tally(skills),
        "skills": [
            {
                "name": skill.name,
                "path": skill.path,
                "packs": sorted(skill.packs),
                "status": skill.status,
                "distribution": skill.distribution,
                "license": skill.license,
                "requires": skill.requires,
                "triggers": skill.triggers,
                "neighbor": skill.neighbor,
            }
            for skill in skills
        ],
    }
    return json.dumps(index, indent=2, sort_keys=True) + "\n"


def write_lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    temporary.replace(path)


def replace_block(text: str, block_id: str, content: str) -> str | None:
    pattern = re.compile(
        rf"(<!-- gen:{re.escape(block_id)} -->)(.*?)(<!-- /gen:{re.escape(block_id)} -->)",
        re.DOTALL,
    )
    if not pattern.search(text):
        return None
    return pattern.sub(lambda match: f"{match.group(1)}\n{content}\n{match.group(3)}", text)


def gen_routing_views(root: Path, check: bool) -> tuple[list[str], list[str], list[str]]:
    """Refresh the generated tables inside base-routing.md. Returns (drift, problems, notes)."""
    drift: list[str] = []
    notes: list[str] = []
    source_path = Path(root) / rp.SOURCE
    if not source_path.is_file():
        notes.append(f"{rp.SOURCE.as_posix()} absent; routing views skipped")
        return drift, [], notes
    try:
        policy = rp.load_policy(root)
    except rp.PolicyError as exc:
        return drift, [f"routing-policy: {exc}"], notes
    source = source_path.read_text(encoding="utf-8-sig")
    updated = source
    for block_id, renderer in ROUTING_BLOCKS.items():
        next_text = replace_block(updated, block_id, renderer(policy))
        if next_text is None:
            notes.append(f"{rp.SOURCE.as_posix()}: markers for '{block_id}' not found; view not written")
        else:
            updated = next_text
    if updated != source:
        drift.append(f"{rp.SOURCE.as_posix()} [routing-views]")
        if not check:
            write_lf(source_path, updated)
    return drift, [], notes


def generate(root: Path = ROOT, check: bool = False) -> tuple[list[str], list[str], list[str]]:
    """Write (or, with check, compare) every generated view. Returns (drift, problems, notes)."""
    root = Path(root)
    skills = scan_skills(root)
    problems = [f"{skill.path}: {problem}" for skill in skills for problem in skill.problems]
    drift: list[str] = []
    notes: list[str] = []
    if not (root / SKILLS_DIR).is_dir():
        notes.append(f"{SKILLS_DIR.as_posix()} absent; resolver rendered empty")

    outputs = {
        RESOLVER: render_resolver(skills),
        SKILL_INDEX: render_skill_index(skills),
        THIRD_PARTY: render_third_party(root),
    }
    for relative, want in outputs.items():
        target = root / relative
        have = target.read_text(encoding="utf-8-sig") if target.is_file() else None
        if have == want:
            continue
        if have is None and relative in UNTRACKED_OUTPUTS and check:
            notes.append(f"{relative.as_posix()} absent (untracked cache); run without --check to write it")
            continue
        drift.append(relative.as_posix() + ("" if have is not None else " (missing)"))
        if not check:
            write_lf(target, want)

    view_drift, view_problems, view_notes = gen_routing_views(root, check)
    drift.extend(view_drift)
    problems.extend(view_problems)
    notes.extend(view_notes)
    return drift, problems, notes


def _third_party_cell(value: str) -> str:
    """Escape a literal pipe so a stray one in a notice or URL cannot break the table row."""
    return value.replace("|", "\\|")


def render_third_party(root: Path = ROOT) -> str:
    """THIRD-PARTY.md body: one table row per harness/registry/sources.json entry.

    Kept in its own renderer (rather than reusing render_licenses' tab-separated
    form) because the two outputs serve different readers: render_licenses is a
    machine-oriented dump for the scaffold's NOTICE, this is the Markdown table
    THIRD-PARTY.md ships with, header prose and all.
    """
    path = Path(root) / SOURCES
    sources: dict[str, Any] = {}
    if path.is_file():
        try:
            registry = json.loads(path.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            registry = {}
        sources = registry.get("sources", {}) if isinstance(registry, dict) else {}
    rows = []
    for source_id in sorted(sources):
        entry = sources[source_id] if isinstance(sources[source_id], dict) else {}
        assets = entry.get("assets", [])
        assets_cell = ", ".join(str(item) for item in assets) if isinstance(assets, list) else ""
        cells = (
            f"`{source_id}`",
            str(entry.get("origin", "")),
            str(entry.get("license", "")),
            "modified" if entry.get("modified") else "unmodified",
            str(entry.get("notice") or ""),
            assets_cell,
        )
        # An empty cell renders as a single bare space between its bordering
        # pipes (matching the hand-authored table this replaces), not a
        # padded-then-doubled space, so "| |" and never "|  |".
        padded = [f" {_third_party_cell(cell)} " if cell else " " for cell in cells]
        rows.append("|" + "|".join(padded) + "|")
    lines = [
        "<!-- GENERATED by harness/tools/gen_manifest.py from harness/registry/sources.json. "
        "Do not edit by hand; edit sources.json and regenerate. -->",
        "",
        "# Third-party notices",
        "",
        "Every vendored or adapted asset in this repository is listed here with its origin, license, "
        "and modification status. The table is regenerated from `harness/registry/sources.json`; "
        "`python harness/tools/gen_manifest.py --check` fails when the two disagree.",
        "",
        "| Source | Origin | License | Modified | Notice | Assets |",
        "|---|---|---|---|---|---|",
    ]
    lines.extend(rows)
    return "\n".join(lines) + "\n"


def render_licenses(root: Path = ROOT) -> str:
    """One line per sources.json entry, for the scaffold's NOTICE and THIRD-PARTY.md."""
    path = Path(root) / SOURCES
    lines = ["# id\torigin\tlicense\tmodified\tassets\tnotice"]
    if not path.is_file():
        return "\n".join(lines) + "\n"
    registry = json.loads(path.read_text(encoding="utf-8-sig"))
    sources = registry.get("sources", {}) if isinstance(registry, dict) else {}
    for source_id in sorted(sources):
        entry = sources[source_id] if isinstance(sources[source_id], dict) else {}
        assets = entry.get("assets", [])
        lines.append("\t".join([
            source_id,
            str(entry.get("origin", "")),
            str(entry.get("license", "")),
            "modified" if entry.get("modified") else "unmodified",
            ", ".join(assets) if isinstance(assets, list) else "",
            str(entry.get("notice") or ""),
        ]))
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the skill resolver, skill index, THIRD-PARTY.md, and routing views.")
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated file would change")
    parser.add_argument("--licenses", action="store_true", help="print license lines from sources.json and exit")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.licenses:
        sys.stdout.write(render_licenses(root))
        return 0
    drift, problems, notes = generate(root, check=args.check)
    for note in notes:
        print(f"NOTE     {note}")
    for problem in problems:
        print(f"PROBLEM  {problem}")
    for item in drift:
        print(f"{'DRIFT' if args.check else 'UPDATED'}  {item}")
    if not drift and not problems:
        print("OK  resolver, skill index, THIRD-PARTY.md, and routing views in sync")
    return 1 if (args.check and drift) or problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
