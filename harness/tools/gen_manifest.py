# ---------------------------------------------------------------------------
# Frontmatter (a deliberately small YAML subset: scalars, block scalars,
# nested mappings by indentation, inline and block lists, quotes, null/bools)
# ---------------------------------------------------------------------------

def _scalar(raw: str) -> Any:
    value = raw.strip()
    if value == "" or value in {"null", "~"}:
        return None
    if value in {"true", "True"}:
        return True
    if value in {"false", "False"}:
        return False
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        inner = value[1:-1]
        return inner.replace('\\"', '"') if value[0] == '"' else inner
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return []
        return [_scalar(item) for item in _split_inline_list(inner)]
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    return value


def _split_inline_list(inner: str) -> list[str]:
    items, current, quote = [], [], None
    for character in inner:
        if quote:
            current.append(character)
            if character == quote:
                quote = None
        elif character in "\"'":
            quote = character
            current.append(character)
        elif character == ",":
            items.append("".join(current))
            current = []
        else:
            current.append(character)
    if current or items:
        items.append("".join(current))
    return [item for item in items if item.strip()]


def _strip_comment(line: str) -> str:
    quote = None
    for index, character in enumerate(line):
        if quote:
            if character == quote:
                quote = None
        elif character in "\"'":
            quote = character
        elif character == "#" and (index == 0 or line[index - 1] in " \t"):
            return line[:index].rstrip()
    return line.rstrip()


def parse_yaml_block(lines: list[str]) -> Any:
    """Parse a mapping or list from indented lines. Returns dict, list, or scalar."""
    cleaned = [(line, _strip_comment(line)) for line in lines]
    cleaned = [(raw, text) for raw, text in cleaned if text.strip()]
    if not cleaned:
        return {}
    indent = min(len(text) - len(text.lstrip(" ")) for _, text in cleaned)
    entries = [(raw, text[indent:]) for raw, text in cleaned]
    if all(text.startswith("- ") or text == "-" for _, text in entries):
        return _parse_list(entries)
    return _parse_mapping(entries)


def _child_lines(entries: list[tuple[str, str]], start: int) -> tuple[list[str], int]:
    children = []
    index = start
    while index < len(entries):
        text = entries[index][1]
        if text.startswith(" "):
            children.append(text)
            index += 1
        else:
            break
    return children, index


def _parse_list(entries: list[tuple[str, str]]) -> list[Any]:
    values: list[Any] = []
    index = 0
    while index < len(entries):
        text = entries[index][1]
        body = text[2:] if text.startswith("- ") else ""
        children, index = _child_lines(entries, index + 1)
        if body and ":" in body and not body.lstrip().startswith(("\"", "'", "[")) and re.match(r"^[\w.-]+:\s", body + " "):
            nested = [body] + [child[2:] if child.startswith("  ") else child.lstrip() for child in children]
            values.append(parse_yaml_block(nested))
        elif children:
            values.append(parse_yaml_block(children))
        else:
            values.append(_scalar(body))
    return values


def _parse_mapping(entries: list[tuple[str, str]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    index = 0
    while index < len(entries):
        text = entries[index][1]
        match = re.match(r"^([\w.-]+):(.*)$", text)
        if not match:
            index += 1
            continue
        key, rest = match.group(1), match.group(2).strip()
        children, index = _child_lines(entries, index + 1)
        if rest in {">", "|", ">-", "|-"}:
            folded = rest.startswith(">")
            parts = [child.strip() for child in children]
            result[key] = (" ".join(parts) if folded else "\n".join(parts)).strip()
        elif rest == "":
            result[key] = parse_yaml_block(children) if children else None
        else:
            result[key] = _scalar(rest)
    return result


def parse_frontmatter(text: str) -> dict[str, Any] | None:
    """Return the frontmatter mapping, or None when the file has no block."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    try:
        closing = next(index for index, line in enumerate(lines[1:], 1) if line.strip() == "---")
    except StopIteration:
        return None
    value = parse_yaml_block(lines[1:closing])
    return value if isinstance(value, dict) else {}


